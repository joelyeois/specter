import torch
from .rotations import Rotation


def get_rotation_matrices(sym, return_affine=True):
    sym = sym.upper()

    if sym[0] == "D":
        n = int(sym[1])
        angs = torch.linspace(0, 360, n + 1)[:-1] / 180 * torch.pi

        vecz = torch.tensor([0, 0, 1])  # [x,y,z]

        # D-syms have additional 180 symmetry around y.
        vecy = torch.tensor([0, 1, 0])  # [x,y,z]
        quaty = torch.tensor(
            [
                torch.sin(torch.tensor(torch.pi / 2)) * vecy[0],
                torch.sin(torch.tensor(torch.pi / 2)) * vecy[1],
                torch.sin(torch.tensor(torch.pi / 2)) * vecy[2],
                torch.cos(torch.tensor(torch.pi / 2)),
            ]
        )
        quaty = Rotation.from_quat(quaty)
        matrices = []
        for ang in angs:
            # rotation around z
            quatz = torch.tensor(
                [
                    torch.sin(torch.tensor(ang / 2)) * vecz[0],
                    torch.sin(torch.tensor(ang / 2)) * vecz[1],
                    torch.sin(torch.tensor(ang / 2)) * vecz[2],
                    torch.cos(torch.tensor(ang / 2)),
                ]
            )
            quatz = Rotation.from_quat(quatz)
            matrices.append(quatz.as_matrix())

            # followed by 180 rotation around y
            matrices.append((quatz * quaty).as_matrix())
        matrices = torch.stack(matrices)

