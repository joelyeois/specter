"""
Filament orientation: a frame carried along the path, plus an accumulated
helical twist about the tangent -- the screw-symmetry construction (translate
along the filament axis, rotate about it) real helical polymers like F-actin
and microtubule protofilaments use.

Each monomer's frame is the path's parallel-transport frame
(``_frames.parallel_transport_frames``), which aligns the template's ``+Z``
with the local tangent and adds no roll of its own as the path bends. On a
straight path that is the plain screw; on a bent one consecutive monomers
differ by the bend and the twist only. The twist is the only roll a monomer
gets, which matters most for a subunit that sits off the axis: an F-actin
subunit 15.7 A out would be displaced by any spurious roll. Rotating ``+Z``
onto each tangent independently, as this module did before, has no such
property: that rotation is singular for a tangent along ``-Z``, and on a
path skirting it the roll it added moved F-actin subunits up to 12 A out of
place (``tests/test_filament_placement.py``).

This module only computes those rotations. How a monomer's own
coordinates are put into the frame they act on is a separate, earlier step
in ``TomogramSpecimenGenerator._render_filament_instances``, chosen per
species by `FilamentSpec.frame`:

* ``"actin_filament"`` lifts one subunit out of a deposited filament model
  already in the filament frame (``_actin.extract_actin_subunit``), so its
  distance from the axis and its orientation are the deposited ones.
* ``"microtubule_dimer"`` lifts one alpha-beta tubulin dimer out of a
  deposited microtubule in the microtubule frame
  (``_tubulin.extract_mt_dimer``): ``+Z`` along its protofilament toward
  the plus end, the origin midway between its two monomers on the
  protofilament's own axis, ``+X`` the direction that pointed away from the
  tube axis in the source lattice.

Both extracted modes render the subunit's coordinates as written, with the
copy's path point at the extracted file's origin
(`subunit_centre_in_filament_frame` undoes the re-centring `PDB` applies).
* ``"principal_axis"`` pre-rotates an isolated monomer's coordinates via
  ``specter.specimen.membrane._placement.align_principal_axis_to_z``: a
  fetched PDB's native axes have no relationship to its stacking direction,
  so its longest principal axis stands in for it, centred on the filament
  axis. That is an approximation (a true docking axis comes from the
  inter-subunit contacts, not a monomer's own inertia tensor), at the level
  of fidelity CTS's own WIP filament code aimed for.
"""

from __future__ import annotations

import math

import gemmi
import numpy as np
import roma
import torch

from ._frames import parallel_transport_frames


def filament_tangents(positions_xyz: torch.Tensor) -> torch.Tensor:
    """
    Per-monomer unit tangent along a filament path.

    Parameters
    ----------
    positions_xyz : torch.Tensor
        Monomer-center positions, shape ``(n, 3)``, physical ``(x, y, z)``.

    Returns
    -------
    torch.Tensor
        Unit tangents, shape ``(n, 3)``. Tangent ``i`` points from monomer
        ``i`` towards monomer ``i + 1`` for all but the last monomer, which
        reuses the second-to-last tangent (no outgoing segment exists at the
        end of the path). A single-monomer path gets an arbitrary tangent
        of ``(0, 0, 1)``.
    """
    n = positions_xyz.shape[0]
    if n == 1:
        return torch.tensor([[0.0, 0.0, 1.0]])
    diffs = positions_xyz[1:] - positions_xyz[:-1]
    tangents = diffs / diffs.norm(dim=-1, keepdim=True).clamp_min(1e-8)
    return torch.cat([tangents, tangents[-1:]], dim=0)


def filament_orientations(
    positions_xyz: torch.Tensor, twist_deg: float
) -> torch.Tensor:
    """
    Per-monomer rotation matrices: the path's parallel-transport frame, then
    an accumulated helical twist about the tangent.

    Parameters
    ----------
    positions_xyz : torch.Tensor
        Monomer positions along the filament axis, shape ``(n, 3)``,
        physical ``(x, y, z)`` (as generated by ``generate_filament_path``).
    twist_deg : float
        Helical twist per monomer, degrees, accumulated along the filament
        (monomer ``i``'s spin is ``i * twist_deg``, by the right-hand rule
        about the tangent, i.e. about the direction of growth). Positive
        builds a right-handed helix, negative a left-handed one. 0 for a
        filament with no twist along a single strand (e.g. a microtubule
        protofilament); -166.6 degrees for F-actin, whose one-start helix
        is left-handed.

    Returns
    -------
    torch.Tensor
        Rotation matrices, shape ``(n, 3, 3)``, physical ``(x, y, z)``
        convention, mapping template coordinates to world coordinates:
        monomer ``i``'s atom at template offset ``c`` from the filament
        axis lands at ``positions_xyz[i] + R[i] @ c``, and each
        ``R[i] @ [0, 0, 1]`` equals tangent ``i``. Consecutive matrices
        differ by the parallel transport of the frame plus `twist_deg`
        about the tangent, and by nothing else. `rotate_volume` moves
        density by the TRANSPOSE of the matrix it is given, so a renderer
        passes ``R[i].T`` to `build_affine_matrix` (see
        ``TomogramSpecimenGenerator._render_filament_instances``).
    """
    frames = parallel_transport_frames(positions_xyz)
    n = positions_xyz.shape[0]
    z_hat = torch.tensor([0.0, 0.0, 1.0], dtype=frames.dtype)
    angles = torch.arange(n, dtype=frames.dtype) * math.radians(twist_deg)
    spins = roma.rotvec_to_rotmat(angles.unsqueeze(1) * z_hat)
    return frames @ spins


def subunit_centre_in_filament_frame(
    path: str, coordinates: torch.Tensor, atomic_numbers: torch.Tensor
) -> torch.Tensor:
    """
    Where a centred copy of an extracted subunit has its origin, in the
    filament frame.

    `PDB` re-centres every structure on its own centroid, which moves a
    subunit written by `extract_actin_subunit` or `extract_mt_dimer` off
    the origin its file was written about: the point on the filament axis
    level with an actin subunit, 15.7 A from its centre, or the midpoint of
    a tubulin dimer's two monomers, a fraction of an Angstrom from the
    dimer's all-atom centroid. Rendering then needs that centroid's
    position in the filament frame, so a copy can be put back where the
    subunit sits.

    Parameters
    ----------
    path : str
        The extracted subunit, as `extract_actin_subunit` or
        `extract_mt_dimer` returns it. Every chain in the file counts.
    coordinates : torch.Tensor
        `PDB`'s centred coordinates of the same file, shape ``(n, 3)``.
    atomic_numbers : torch.Tensor
        `PDB`'s atomic numbers, shape ``(n,)``.

    Returns
    -------
    torch.Tensor
        The centroid of `coordinates` in the filament frame, shape ``(3,)``,
        physical ``(x, y, z)`` in Å: ``(r, 0, 0)`` for an actin subunit up
        to the hydrogens `PDB` may have added.

    Raises
    ------
    ValueError
        If the parsed structure and the file hold different numbers of
        heavy atoms, so the shift `PDB` applied cannot be recovered.

    Notes
    -----
    Compared on heavy atoms only: `PDB` may add hydrogens the file does not
    hold, but keeps its heavy atoms, and the difference of the two
    heavy-atom centroids is exactly the shift `PDB` applied.
    """
    st = gemmi.read_structure(path)
    file_heavy = np.array(
        [
            [a.pos.x, a.pos.y, a.pos.z]
            for chain in st[0]
            for res in chain
            for a in res
            if a.element.atomic_number > 1
        ]
    )
    heavy = atomic_numbers > 1
    if int(heavy.sum()) != len(file_heavy):
        raise ValueError(
            f"{path}: the parsed structure holds {int(heavy.sum())} heavy atoms "
            f"and the file {len(file_heavy)}, so its centring cannot be undone"
        )
    centre = file_heavy.mean(axis=0) - coordinates[heavy].double().mean(0).numpy()
    return torch.tensor(centre, dtype=torch.float32)
